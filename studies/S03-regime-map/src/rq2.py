def cmd_probe_controls() -> None:
    """Record, as a committed artifact, which sampling/determinism controls each
    hosted model under study actually accepts (RQ2: 'what do the exposed
    determinism controls actually do' begins with 'which ones exist'). Each probe
    is one minimal real call; rejections are captured verbatim."""
    import urllib.error

    def probe(vendor: str, extra: dict) -> dict:
        sys_p = "Reply with the single word: ok"
        try:
            if vendor == "openai":
                body = {"model": "gpt-5.6-luna", "max_completion_tokens": 20,
                        "messages": [{"role": "system", "content": sys_p},
                                     {"role": "user", "content": "go"}], **extra}
                req = urllib.request.Request(
                    "https://api.openai.com/v1/chat/completions",
                    data=json.dumps(body).encode(),
                    headers={"Content-Type": "application/json",
                             "Authorization": f"Bearer {__import__('os').environ['OPENAI_API_KEY']}"})
            else:
                body = {"model": "claude-sonnet-5", "max_tokens": 20,
                        "system": sys_p,
                        "messages": [{"role": "user", "content": "go"}], **extra}
                req = urllib.request.Request(
                    "https://api.anthropic.com/v1/messages",
                    data=json.dumps(body).encode(),
                    headers={"Content-Type": "application/json",
                             "x-api-key": __import__('os').environ["ANTHROPIC_API_KEY"],
                             "anthropic-version": "2023-06-01"})
            with urllib.request.urlopen(req, timeout=60) as r:
                payload = json.load(r)
            return {"vendor": vendor, "params": extra, "accepted": True,
                    "model_id": payload.get("model"),
                    "usage": payload.get("usage", {})}
        except urllib.error.HTTPError as e:
            try:
                err = json.loads(e.read()).get("error", {}).get("message", "")
            except Exception:
                err = "<unreadable body>"
            return {"vendor": vendor, "params": extra, "accepted": False,
                    "http_status": e.code, "error_message": err}

    probes = [
        ("openai", {}), ("openai", {"seed": 42}), ("openai", {"temperature": 0.0}),
        ("openai", {"temperature": 1.0}), ("openai", {"top_p": 0.01}),
        ("anthropic", {}), ("anthropic", {"temperature": 0.0}),
        ("anthropic", {"temperature": 0.5}), ("anthropic", {"temperature": 1}),
        ("anthropic", {"top_k": 1}), ("anthropic", {"top_p": 0.01}),
    ]
    results = [probe(v, p) for v, p in probes]
    art = {"purpose": "Which exposed sampling/determinism controls each hosted "
                      "model under study accepts (PROTOCOL Sec. 4 ladder, v1.4; "
                      "D-016). One minimal real call per row; rejections verbatim.",
           "results": results}
    write_json(PROBE_OUT, art)
    for r in results:
        tag = "ACCEPTED" if r["accepted"] else f"HTTP {r['http_status']}: {r['error_message']}"
        print(f"{r['vendor']:>9} {json.dumps(r['params']):<22} -> {tag}")
    print(f"wrote {PROBE_OUT.name}")


