"""RQ2 reproducibility ladder (PROTOCOL Secs. 1/4/6/7, block D).

Question: given byte-identical inputs, how reproducible are the controller's
decisions and outputs across serving configurations, and what do the exposed
determinism controls actually do?

Probe states are REAL block-C states, not synthetic (S01 D-045 lesser finding;
PROTOCOL Sec. 6): each sampled state is regenerated by replaying a block-C
episode's recorded decision sidecar through the deterministic plant, which
reproduces byte-for-byte the observation/history prompt the controller saw at
that instant. Replay fidelity is verified per episode by exact match of the
replayed metrics against the recorded sweep.jsonl row; episodes that do not
replay exactly (e.g. an API-error retry whose latency was not recorded) are
excluded from sampling and counted.

Serving configurations (PROTOCOL Sec. 4 ladder, v1.3b sizing):
  local-serial    llama-server :8200, --parallel 1, temperature 0, seed 42
  local-batched   llama-server :8200, --parallel 4, temperature 0, seed 42,
                  repeats fired in concurrent waves of 4 (continuous batching on)
  luna-default    gpt-5.6-luna, vendor-default sampling, no seed
  luna-seeded     gpt-5.6-luna, seed=42 (the documented determinism control)
  sonnet-default  claude-sonnet-5, vendor-default sampling

A sonnet-pinned rung was pre-registered (PROTOCOL Sec. 4 ladder) and is
UNRUNNABLE: claude-sonnet-5 rejects temperature != 1, top_k, and top_p with
HTTP 400 "deprecated for this model" — the vendor exposes no determinism
control at all for its newest generation. Probed mechanically by
`rq2.py probe-controls` (artifact: results/rq2_determinism_probe.json);
PROTOCOL Sec. 13 v1.4; DECISIONS D-016. The missing rung is a finding, not
a gap: the reproducibility ladder's hosted rungs are default-sampling only
for this vendor, and the released evidence records exactly that.

Repeats: 30 per state for local + luna configs, 20 for sonnet (v1.3b last
reduction step). max_tokens matches the sweep (hosted 300 / local 400) so the
prompt-economics regime is identical to block C.

Metrics per (config, state): byte-identity rate (modal raw output share),
decision-identity rate (modal (replicas, variant) share), normalised entropy of
the scale direction {up, hold, down} vs the state's current replicas,
Delta-replicas dispersion (max-min), self-contradiction rate (both up and down
seen for the same input), parse-failure count. Computed in analyze.py from the
raw rq2.jsonl; this script only records evidence.

Usage:
  python3 rq2.py sample                      # replay C sidecars -> rq2_states.json
  python3 rq2.py hosted [--config NAME]      # luna/sonnet configs (API spend)
  python3 rq2.py local-serial                # needs :8200 with --parallel 1
  python3 rq2.py local-batched               # needs :8200 with --parallel 4
  python3 rq2.py selfcheck                   # offline; no API, no server

Resume-safe: results/rq2.jsonl keyed (config, state_id, repeat); existing keys
are skipped. Hosted spend goes through the same SpendLedger ($60 backstop).
"""
