# ------------------------------------------------------------------ replay

class ReplayController:
    """Feeds an episode's recorded actions back to the plant and captures the
    byte-identical (observation, history) prompt at every decision instant."""
    name = "replay"

    def __init__(self, groups: list[dict]):
        self.groups = groups          # one entry per decision instant, in order
        self.idx = 0
        self.captured: list[dict] = []
        self.mismatch = False

    def decide(self, obs, history) -> Action:
        if self.idx >= len(self.groups):
            self.mismatch = True      # plant asked for more decisions than recorded
            return Action(replicas=obs.replicas, variant=obs.variant, parse_failed=True)
        g = self.groups[self.idx]
        self.idx += 1
        if abs(g["t"] - obs.t) > 1e-6:
            self.mismatch = True
        act = g["action"]
        if act is None:               # recorded parse failure -> fallback hold
            act = Action(replicas=obs.replicas, variant=obs.variant, parse_failed=True)
        act.latency_s = g["latency_s"]
        act.tokens_in, act.tokens_out, act.usd = g["tokens_in"], g["tokens_out"], g["usd"]
        self.captured.append({
            "t": obs.t,
            "user": render_observation(obs) + "\n" + render_history(history),
            "obs": {"replicas": obs.replicas, "variant": obs.variant,
                    "queue_len": obs.queue_len, "p95_ms": obs.p95_ms,
                    "utilization": obs.utilization,
                    "arrival_rate": obs.arrival_rate},
        })
        return act


def group_sidecar(entries: list[dict]) -> tuple[list[dict], bool]:
    """Group per-call sidecar entries into per-decision records, replicating
    LLMController.decide: attempts at the same t, first parseable wins; latency
    is the sum across attempts. Returns (groups, clean); clean=False if any
    attempt lacks a recorded latency (API-error entries) so replay would drift."""
    groups: list[dict] = []
    clean = True
    for e in entries:
        if not groups or abs(e["t"] - groups[-1]["t"]) > 1e-9 or groups[-1]["done"]:
            if groups and not groups[-1]["done"]:
                pass                  # previous decision ended in parse failure
            if groups and abs(e["t"] - groups[-1]["t"]) <= 1e-9 and groups[-1]["done"]:
                clean = False         # extra call at same t after success: unexpected
            groups.append({"t": e["t"], "action": None, "latency_s": 0.0,
                           "tokens_in": 0, "tokens_out": 0, "usd": 0.0,
                           "done": False})
        g = groups[-1]
        if "latency_s" in e:
            g["latency_s"] += e["latency_s"]
        else:
            clean = False             # error entry without recorded latency
        g["usd"] += e.get("usd", 0.0)
        u = (e.get("meta") or {}).get("usage") or {}
        g["tokens_in"] += u.get("prompt_tokens") or 0
        g["tokens_out"] += u.get("completion_tokens") or 0
        if "raw" in e and not g["done"]:
            try:
                g["action"] = parse_action(e["raw"], None)
                g["done"] = True
            except Exception:
                pass
    for g in groups:
        g.pop("done", None)
    return groups, clean


def replay_episode(design, cal, row: dict) -> ReplayController | None:
    """Replay one block-C episode from its sidecar; return the controller with
    captured prompts iff the replayed metrics exactly match the recorded row."""
    sidecar = DECDIR / (row["key"].replace("|", "_") + ".json.gz")
    if not sidecar.exists():
        return None
    with gzip.open(sidecar, "rt") as f:
        entries = json.load(f)
    groups, clean = group_sidecar(entries)
    if not clean:
        return None
    cfg = episode_cfg(design, float(row["cadence_s"]))
    arrivals, _ = make_trace(design["mean_rate_rps"], row["I"], cfg.horizon_s,
                             row["seed"])
    ctl = ReplayController(groups)
    plant = Plant(cal, cfg, plant_seed=row["seed"])
    m = plant.run(list(arrivals), ctl, init_replicas=design["init_replicas"],
                  init_variant=design["init_variant"])
    rec = row["metrics"]
    exact = (not ctl.mismatch
             and abs(m["U_S03"] - rec["U_S03"]) < 1e-9
             and m["offered"] == rec["offered"]
             and m["completed"] == rec["completed"]
             and m["controller"]["invocations"] == rec["controller"]["invocations"])
    return ctl if exact else None


# ------------------------------------------------------------------ sampling

def stratum_of(obs: dict, slo_ms: float) -> str:
    """Mechanical strata (fixed before sampling): near-threshold states sit at
    the decision boundary (p95 within +-20% of SLO, or utilisation 0.75-0.95);
    clear-cut states are unambiguous (deep overload or deep calm); the rest are
    'other' and not sampled."""
    p95, util, q = obs["p95_ms"], obs["utilization"], obs["queue_len"]
    if p95 is not None and 0.8 * slo_ms <= p95 <= 1.2 * slo_ms:
        return "near"
    if 0.75 <= util <= 0.95:
        return "near"
    if (p95 is not None and p95 > 1.5 * slo_ms) or q >= 20:
        return "clear-overload"
    if (p95 is None or p95 < 0.5 * slo_ms) and q == 0 and util < 0.5:
        return "clear-calm"
    return "other"


def cmd_sample(design, cal) -> None:
    rows = []
    for line in SWEEP.read_text().splitlines():
        try:
            r = json.loads(line)
        except Exception:
            continue
        if r.get("block") == "C" and r.get("model") == "gpt-5.6-luna":
            rows.append(r)
    print(f"{len(rows)} luna block-C episodes on disk")
    system = make_intent("full", slo_ms=design["slo_ms"], abandon_s=design["abandon_s"],
                         max_replicas=design["max_replicas"],
                         variant_menu=menu_text(design),
                         switch_s=max(design["switch_load_s"].values())
                         ) + "\n\n" + RESPONSE_SPEC
    pool = {"near": [], "clear-overload": [], "clear-calm": []}
    replayed = failed = 0
    for row in rows:
        ctl = replay_episode(design, cal, row)
        if ctl is None:
            failed += 1
            continue
        replayed += 1
        for cap in ctl.captured:
            if cap["t"] < design["warmup_exclude_s"]:
                continue              # scored span only (R6)
            s = stratum_of(cap["obs"], design["slo_ms"])
            if s in pool:
                pool[s].append({**cap, "stratum": s, "episode_key": row["key"],
                                "I": row["I"], "cadence_s": row["cadence_s"]})
    print(f"replayed exactly: {replayed}; excluded (non-exact/missing): {failed}")
    for s, lst in pool.items():
        print(f"  stratum {s}: {len(lst)} candidate states")
    # Deterministic spread: 15 near, 8 clear-overload, 7 clear-calm; within each
    # stratum spread across (I, cadence) round-robin, then evenly by index.
    import random as _random
    rng = _random.Random(20260802)
    quota = {"near": 15, "clear-overload": 8, "clear-calm": 7}
    chosen = []
    for s, n in quota.items():
        cands = pool[s]
        if not cands:
            print(f"  WARNING: stratum {s} empty — quota unmet (reported, not hidden)")
            continue
        bycell: dict = {}
        for c in cands:
            bycell.setdefault((c["I"], c["cadence_s"]), []).append(c)
        for lst in bycell.values():
            rng.shuffle(lst)
        cells = sorted(bycell)
        i = 0
        while sum(1 for c in chosen if c["stratum"] == s) < min(n, len(cands)):
            cell = cells[i % len(cells)]
            if bycell[cell]:
                chosen.append(bycell[cell].pop())
            i += 1
            if i > 10000:
                break
    for k, c in enumerate(chosen):
        c["state_id"] = f"st{k:02d}"
    art = {"system": system,
           "replayed_ok": replayed, "replay_excluded": failed,
           "pool_sizes": {s: len(l) for s, l in pool.items()},
           "quota": quota, "states": chosen}
    write_json(STATES, art)
    print(f"wrote {len(chosen)} states -> {STATES.name}")


# ------------------------------------------------------------------ repeats

def server_slots(port: int = LOCAL_PORT) -> int:
    with urllib.request.urlopen(f"http://127.0.0.1:{port}/props", timeout=5) as r:
        props = json.load(r)
    n = props.get("total_slots") or props.get("n_parallel") \
        or (props.get("default_generation_settings") or {}).get("n_parallel")
    if n is None:
        raise RuntimeError(f"cannot determine slot count from /props: {props}")
    return int(n)


def one_call(config: str, system: str, user: str) -> dict:
    """One repeat. Transient API errors are retried (the sweep's known luna
    HTTP-400 flake killed the first hosted run — chain log 2026-08-03); a call
    still failing after retries is RECORDED as an errored row, never raised —
    API errors are a counted failure mode (PROTOCOL Sec. 8b), and one flake
    must not kill a 2,400-call config."""
    t0 = time.monotonic()
    text = meta = None
    last_err = None
    for attempt in range(3):
        try:
            if config == "luna-default":
                text, meta = _openai_call("gpt-5.6-luna", system, user, seed=None)
            elif config == "luna-seeded":
                text, meta = _openai_call("gpt-5.6-luna", system, user, seed=42)
            elif config == "sonnet-default":
                text, meta = _anthropic_call("claude-sonnet-5", system, user, seed=None)
            elif config in ("local-serial", "local-batched"):
                text, meta = _local_call("local-3B", system, user, seed=42,
                                         port=LOCAL_PORT, temperature=0.0)
            else:
                raise ValueError(config)
            break
        except ValueError:
            raise
        except Exception as e:
            last_err = str(e)
            time.sleep(min(4.0, 2.0 ** attempt))
    latency = time.monotonic() - t0
    if text is None:
        return {"raw": None, "meta": None, "latency_s": latency, "usd": 0.0,
                "parsed": None, "parse_error": None,
                "api_error": f"failed after 3 attempts: {last_err}"}
    usd = 0.0
    if config.startswith(("luna", "sonnet")):
        billed = "gpt-5.6-luna" if config.startswith("luna") else "claude-sonnet-5"
        usd = call_cost_usd(billed, meta.get("usage") or {})
        if usd > 0:
            LEDGER.add(billed, usd)
    parsed = None
    err = None
    try:
        a = parse_action(text, None)
        parsed = {"replicas": a.replicas, "variant": a.variant,
                  "repaired": a.repaired}
    except Exception as e:
        err = str(e)
    return {"raw": text, "meta": meta, "latency_s": latency, "usd": usd,
            "parsed": parsed, "parse_error": err}


def existing() -> set:
    keys = set()
    if OUT.exists():
        for line in OUT.read_text().splitlines():
            try:
                keys.add(json.loads(line)["key"])
            except Exception:
                continue
    return keys


def record(key: str, payload: dict) -> None:
    payload["key"] = key
    append_jsonl(OUT, payload)


def run_config(config: str, parallel: int = 1) -> None:
    art = json.loads(STATES.read_text())
    system, states = art["system"], art["states"]
    done = existing()
    jobs = [(s, rep) for s in states for rep in range(REPEATS[config])
            if f"{config}|{s['state_id']}|r{rep}" not in done]
    print(f"{config}: {len(jobs)} calls to run "
          f"({len(states)} states x {REPEATS[config]} repeats, minus done)")

    def run_one(job):
        s, rep = job
        res = one_call(config, system, s["user"])
        return f"{config}|{s['state_id']}|r{rep}", {
            "config": config, "state_id": s["state_id"], "repeat": rep,
            "stratum": s["stratum"], "episode_key": s["episode_key"],
            "t": s["t"], **res}

    if parallel <= 1:
        for job in jobs:
            key, payload = run_one(job)
            record(key, payload)
    else:
        # waves of `parallel` so batched slots genuinely co-schedule
        for i in range(0, len(jobs), parallel):
            wave = jobs[i:i + parallel]
            with ThreadPoolExecutor(max_workers=parallel) as ex:
                for key, payload in ex.map(run_one, wave):
                    record(key, payload)
            if (i // parallel) % 20 == 0:
                print(f"  {min(i + parallel, len(jobs))}/{len(jobs)}", flush=True)
    print(f"{config} complete")


