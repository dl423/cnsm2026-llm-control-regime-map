def cmd_selfcheck(design, cal) -> None:
    """Offline: the replay harness must reproduce a scripted episode exactly,
    and the stratum classifier must behave at its boundaries."""
    cfg = episode_cfg(design, 60.0)
    arrivals, _ = make_trace(design["mean_rate_rps"], 400.0, cfg.horizon_s, 424242)

    class Scripted:
        name = "scripted"
        def __init__(self):
            self.log = []
        def decide(self, obs, history):
            r = 1 + (int(obs.t) // 300) % 3
            v = ["tiny-1B4", "full-3B", "lite-1B"][(int(obs.t) // 600) % 3]
            raw = json.dumps({"replicas": r, "variant": v, "why": "scripted"})
            self.log.append({"t": obs.t, "attempt": 0, "raw": raw,
                             "meta": {"usage": {"prompt_tokens": 10,
                                                "completion_tokens": 5}},
                             "latency_s": 1.5, "usd": 0.0})
            a = Action(replicas=r, variant=v, raw=raw)
            a.latency_s = 1.5
            return a

    sc = Scripted()
    m1 = Plant(cal, cfg, plant_seed=424242).run(
        list(arrivals), sc, design["init_replicas"], design["init_variant"])
    groups, clean = group_sidecar(sc.log)
    assert clean and len(groups) == m1["controller"]["invocations"]
    ctl = ReplayController(groups)
    m2 = Plant(cal, cfg, plant_seed=424242).run(
        list(arrivals), ctl, design["init_replicas"], design["init_variant"])
    assert not ctl.mismatch
    assert abs(m1["U_S03"] - m2["U_S03"]) < 1e-12, (m1["U_S03"], m2["U_S03"])
    assert m1["offered"] == m2["offered"] and m1["completed"] == m2["completed"]
    assert len(ctl.captured) == len(groups)
    assert all("STATE t=" in c["user"] for c in ctl.captured)
    # parse-failure grouping: two failed attempts then one success at same t
    bad = [{"t": 60.0, "attempt": 0, "raw": "gibberish", "latency_s": 1.0,
            "meta": {"usage": {}}, "usd": 0.0},
           {"t": 60.0, "attempt": 1, "raw": '{"replicas": 3, "variant": "full-3B", '
            '"why": "ok"}', "latency_s": 2.0, "meta": {"usage": {}}, "usd": 0.0}]
    g2, clean2 = group_sidecar(bad)
    assert clean2 and len(g2) == 1 and g2[0]["action"].replicas == 3
    assert abs(g2[0]["latency_s"] - 3.0) < 1e-12
    # stratum boundaries
    slo = design["slo_ms"]
    assert stratum_of({"p95_ms": slo, "utilization": 0.2, "queue_len": 0}, slo) == "near"
    assert stratum_of({"p95_ms": 2 * slo, "utilization": 1.0, "queue_len": 50},
                      slo) == "clear-overload"
    assert stratum_of({"p95_ms": None, "utilization": 0.1, "queue_len": 0},
                      slo) == "clear-calm"
    assert stratum_of({"p95_ms": 0.6 * slo, "utilization": 0.6, "queue_len": 2},
                      slo) == "other"
    print("rq2 offline self-checks PASS (replay exact; grouping; strata)")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["sample", "hosted", "local-serial",
                                    "local-batched", "selfcheck", "probe-controls"])
    ap.add_argument("--config", default=None,
                    help="hosted only: run a single named config")
    args = ap.parse_args()
    design = load_design()
    cal = build_cal(design)
    if args.cmd == "sample":
        cmd_sample(design, cal)
    elif args.cmd == "selfcheck":
        cmd_selfcheck(design, cal)
    elif args.cmd == "probe-controls":
        cmd_probe_controls()
    elif args.cmd == "hosted":
        configs = ([args.config] if args.config else
                   ["luna-seeded", "luna-default", "sonnet-default"])
        for c in configs:
            run_config(c, parallel=4)
    elif args.cmd == "local-serial":
        n = server_slots()
        assert n == 1, f"local-serial needs --parallel 1 server, found {n} slots"
        run_config("local-serial", parallel=1)
    elif args.cmd == "local-batched":
        n = server_slots()
        assert n == 4, f"local-batched needs --parallel 4 server, found {n} slots"
        run_config("local-batched", parallel=4)


